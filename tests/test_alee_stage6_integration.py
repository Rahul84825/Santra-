class TestALEEStage6Integration(unittest.TestCase):
    """Verifies end-to-end execution fixes, active rule integration, and PyQt6 Evolution Center."""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.test_db_path = os.path.join(self.temp_dir.name, "test_evolution_s6.db")
        self.storage = EvolutionStorage(db_path=self.test_db_path)
        self.collector = ExperienceCollector(storage=self.storage)
        self.evaluator = PerformanceEvaluator(storage=self.storage, collector=self.collector)
        self.skill_dev = SkillDeveloper(storage=self.storage, collector=self.collector)
        self.evo_mgr = EvolutionManager(
            storage=self.storage,
            evaluator=self.evaluator,
            skill_dev=self.skill_dev,
            collector=self.collector
        )

    def tearDown(self):
        self.collector.shutdown()
        self.storage.close()
        try:
            self.temp_dir.cleanup()
        except Exception:
            pass

    # ==========================================
    # TEST 1: ACTIVE RULE IN-MEMORY RETRIEVAL (<0.05ms)
    # ==========================================
    def test_01_evolution_active_rule_retrieval(self):
        """Verifies get_active_rule() is sub-millisecond and updates synchronously with approval/rollback."""
        # Unapproved rule returns empty dict
        t0 = time.perf_counter()
        rule_empty = self.evo_mgr.get_active_rule("create_file")
        dt_ms = (time.perf_counter() - t0) * 1000
        self.assertEqual(rule_empty, {})
        self.assertLess(dt_ms, 0.05, f"Lookup latency {dt_ms:.4f}ms exceeded 0.05ms budget")

        # Create and approve a rule proposal
        prop_id = self.storage.upsert_proposal({
            "proposal_id": "prop_rule_create_file",
            "proposal_type": "INTENT_RULE",
            "target_key": "create_file",
            "proposed_value": {
                "strategy": "atomic_write_fallback",
                "ensure_parent_dirs": True,
                "auto_overwrite": True
            },
            "reason": "Test active rule wiring",
            "evidence_count": 54,
            "status": "PENDING"
        })

        ok, msg = self.evo_mgr.approve_proposal(prop_id, confirmed_by_user=True)
        self.assertTrue(ok, f"Approval failed: {msg}")

        # In-memory lookup must immediately return the active configuration
        t1 = time.perf_counter()
        active_rule = self.evo_mgr.get_active_rule("create_file")
        dt1_ms = (time.perf_counter() - t1) * 1000

        self.assertIsNotNone(active_rule)
        self.assertTrue(active_rule.get("ensure_parent_dirs"))
        self.assertEqual(active_rule.get("strategy"), "atomic_write_fallback")
        self.assertLess(dt1_ms, 0.05, f"Lookup latency {dt1_ms:.4f}ms exceeded 0.05ms budget")

        # Rollback rule and verify cache clears
        rb_ok, _ = self.evo_mgr.rollback_proposal(prop_id)
        self.assertTrue(rb_ok)
        self.assertEqual(self.evo_mgr.get_active_rule("create_file"), {})

    # ==========================================
    # TEST 2: CREATE_FILE WITH PARENT DIR RESOLUTION
    # ==========================================
    def test_02_create_file_with_parent_dir_resolution(self):
        """Verifies CommandExecutor create_file creates nested parent directories cleanly."""
        nested_dest = os.path.join(self.temp_dir.name, "deep", "nested", "workspace")
        test_filename = "auto_created_script.py"
        test_content = "# Auto generated by ALEE Stage 6\nprint('Execution Verified!')\n"

        executor = CommandExecutor()
        intent_node = {
            "intent": "file_management.create_file",
            "action": "create_file",
            "destination": nested_dest,
            "filename": test_filename,
            "content": test_content,
            "allow_overwrite": True
        }

        res = executor.execute(intent_node=intent_node)
        self.assertTrue(res.get("success"), f"File creation failed: {res.get('message')}")

        target_file = Path(nested_dest) / test_filename
        self.assertTrue(target_file.exists(), f"Target file does not exist at: {target_file}")
        self.assertEqual(target_file.read_text(encoding="utf-8"), test_content)

    # ==========================================
    # TEST 3: LEGACY BRIDGE 'INDEPENDENTLY_VERIFIED' FIX
    # ==========================================
    def test_03_legacy_bridge_independently_verified_success(self):
        """Verifies 'independently_verified' outcomes are imported as success=1."""
        legacy_path = os.path.join(self.temp_dir.name, "mock_legacy.db")
        conn = sqlite3.connect(legacy_path)
        cur = conn.cursor()
        cur.execute("""
            CREATE TABLE execution_experiences (
                id INTEGER PRIMARY KEY,
                timestamp REAL,
                user_request TEXT,
                normalized_intent TEXT,
                tool_or_procedure TEXT,
                execution_parameters TEXT,
                execution_outcome TEXT,
                observed_failure TEXT
            )
        """)
        cur.execute("""
            INSERT INTO execution_experiences VALUES (
                1, 1700000000.0, 'open chrome', 'OPEN_APP', 'open_app',
                '{"app_name": "chrome"}', 'independently_verified', NULL
            )
        """)
        conn.commit()
        conn.close()

        bridge = LegacyMemoryBridge(storage=self.storage)
        res = bridge.sync_legacy_memory(legacy_db_path=legacy_path)
        self.assertEqual(res["synced_experiences"], 1)

        # Verify experience in storage is marked success=1
        with self.storage._lock:
            s_conn = self.storage._get_connection()
            s_cur = s_conn.cursor()
            s_cur.execute("SELECT success, message, error_type FROM experiences WHERE user_request = 'open chrome'")
            row = s_cur.fetchone()
            s_cur.close()

        self.assertIsNotNone(row)
        self.assertEqual(row[0], 1, "independently_verified record must be stored with success=1")
        self.assertIsNone(row[2], "error_type must be NULL for verified executions")

    # ==========================================
    # TEST 4: CLOSE_APPLICATION GRACEFUL HANDLING
    # ==========================================
    def test_04_close_application_graceful_handling(self):
        """Verifies close_app handles pronoun context and non-existent targets gracefully."""
        executor = CommandExecutor()

        # Contextual pronoun target ("it" / "file")
        intent_pronoun = {
            "intent": "close_app",
            "action": "close_application",
            "target": "file"
        }
        res_pronoun = executor.execute(intent_node=intent_pronoun)
        # Should not raise exception
        self.assertIn("success", res_pronoun)

        # Missing target argument
        intent_empty = {
            "intent": "close_app",
            "action": "close_application",
            "target": ""
        }
        res_empty = executor.execute(intent_node=intent_empty)
        self.assertFalse(res_empty.get("success"))
        self.assertIn("Which application", res_empty.get("message", ""))

